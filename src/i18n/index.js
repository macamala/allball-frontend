export const DICTS = { en, sr, es, de, fr, it, pt };

export function canonicalKeys() {
  return Object.keys(en);
}

export function missingKeys(lang) {
  const table = DICTS[lang] || {};
  return canonicalKeys().filter((key) => !table[key]);
}

export function readLanguage() {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    if (DICTS[value]) return value;
  } catch (err) {
    // Ignore unavailable storage.
  }
  return "en";
}

export function writeLanguage(code) {
  const next = DICTS[code] ? code : "en";
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch (err) {
    // Ignore unavailable storage.
  }
  return next;
}

function commentCount(lang, n) {
  const count = Number(n) || 0;
  if (lang === "sr") {
    return count === 1 ? "1 komentar" : `${count} komentara`;
  }
  const table = DICTS[lang] || en;
  const key = count === 1 ? "comments.count.one" : "comments.count.other";
  return (table[key] || en[key]).replaceAll("{n}", String(count));
}

export function translate(lang, key, vars = {}) {
  if (key === "comments.count") {
    return commentCount(lang, vars.n);
  }
  const table = DICTS[lang] || en;
  let value = table[key] || en[key] || key;
  Object.entries(vars).forEach(([name, item]) => {
    value = value.replaceAll(`{${name}}`, String(item));
  });
  return value;
}

export function sportI18nKey(slug) {
  if (slug === "other" || slug === "other-sports") return "sport.other";
  if (["football", "basketball", "tennis", "motorsport"].includes(slug)) {
    return `sport.${slug}`;
  }
  return "";
}
